FRAMEWORK_HAMD = """
## HAMD创作四步法

按以下四步组织整篇脚本结构：

### Hook（传播钩子，占总时长~10%）
- 标题决定点击动机，hook决定前3秒留存
- 必须用：价格对比 / 反常识数据 / 痛点场景 三者之一开场
- 15字以内必须让观众知道"这视频跟我有关"

### Anchor（记忆锚点，占总时长~15%）
- 给观众一个"记住这个视频"的理由
- 核心数字、极端对比、一句话总结——三者至少有其二
- 例："200块和2000块的键盘到底差在哪？答案只有一个字：轴。"

### Mind Map（发散收敛，占总时长~55%）
- 先发散展示所有相关维度（性能/手感/外观/价格/竞品），再收敛到核心推荐
- 每个维度一段，段与段之间用转场钩子连接（"但更关键的还在后面……"）
- 按"从重要到最重要"排序，不是"从外到内"

### Different（差异视角，占总时长~20%）
- 区别于同类内容的独特角度——别人讲参数你讲体验，别人讲体验你讲场景
- 至少1处"你肯定不知道"或"99%的人没注意"的独家发现
- 结尾回顾Anchor，形成闭环
"""

